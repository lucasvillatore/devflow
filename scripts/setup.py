#!/usr/bin/env python3
"""devflow setup: writes the devflow config, creates the Vault skeleton and wires the machine.

Usage:
  python3 setup.py status
  python3 setup.py check
  python3 setup.py apply --language <en|pt-BR> --vault <path> --areas <a,b,...> [--dry-run]

`apply` is idempotent: it only adds missing Vault files, rewrites only its own block in
~/.claude/CLAUDE.md and only its own keys in ~/.claude/settings.json (with a backup).
Standard library only.
"""
import argparse
import datetime
import difflib
import importlib.util
import json
import os
import shutil
import sys

PLUGIN = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HOME = os.path.expanduser("~")
CONFIG = os.path.join(HOME, ".config", "devflow", "config.json")
CLAUDE_DIR = os.path.join(HOME, ".claude")
SETTINGS = os.path.join(CLAUDE_DIR, "settings.json")
CLAUDE_MD = os.path.join(CLAUDE_DIR, "CLAUDE.md")
BACKUPS = os.path.join(CLAUDE_DIR, "backups")
START = "<!-- devflow:start (generated by /devflow:setup; edits inside this block are overwritten) -->"
END = "<!-- devflow:end -->"
SKILL_PREFIX = "Skill(devflow:"


def read_json(path, default):
    if not os.path.exists(path):
        return default
    with open(path, encoding="utf-8") as handle:
        return json.load(handle)


def read_text(path):
    if not os.path.exists(path):
        return ""
    with open(path, encoding="utf-8") as handle:
        return handle.read()


def components():
    return read_json(os.path.join(PLUGIN, "components.json"), {"areas": {}})["areas"]


def languages():
    return sorted(os.listdir(os.path.join(PLUGIN, "templates", "vault")))


def status():
    config = read_json(CONFIG, None)
    settings = read_json(SETTINGS, {})
    vault = os.path.expanduser(config["vault"]) if config and config.get("vault") else None
    report = {
        "plugin": PLUGIN,
        "config_path": CONFIG,
        "config": config,
        "languages": languages(),
        "areas": {name: bool(area.get("required")) for name, area in components().items()},
        "vault_exists": bool(vault and os.path.isdir(vault)),
        "vault_has_kb": bool(vault and os.path.exists(os.path.join(vault, ".kb", "base.yaml"))),
        "auto_memory_enabled": settings.get("autoMemoryEnabled", True),
        "devflow_deny_rules": [r for r in settings.get("permissions", {}).get("deny", []) if r.startswith(SKILL_PREFIX)],
        "claude_md_block": START in read_text(CLAUDE_MD),
        "pyyaml": importlib.util.find_spec("yaml") is not None,
    }
    print(json.dumps(report, indent=2, ensure_ascii=False))


def vault_plan(language, vault):
    source = os.path.join(PLUGIN, "templates", "vault", language)
    missing = []
    for root, _, names in os.walk(source):
        for name in names:
            src = os.path.join(root, name)
            rel = os.path.relpath(src, source)
            if not os.path.exists(os.path.join(vault, rel)):
                missing.append((src, rel))
    return sorted(missing, key=lambda item: item[1])


def settings_plan(areas):
    current = read_json(SETTINGS, {})
    wanted = json.loads(json.dumps(current))
    wanted["autoMemoryEnabled"] = False
    permissions = wanted.setdefault("permissions", {})
    deny = [r for r in permissions.get("deny", []) if not r.startswith(SKILL_PREFIX)]
    for name, area in components().items():
        if name not in areas and not area.get("required"):
            deny += [f"{SKILL_PREFIX}{skill})" for skill in area.get("skills", [])]
    if deny:
        permissions["deny"] = deny
    else:
        permissions.pop("deny", None)
    if not permissions:
        wanted.pop("permissions", None)
    return current, wanted


def claude_md_plan(vault):
    current = read_text(CLAUDE_MD)
    flow = read_text(os.path.join(PLUGIN, "references", "flow.md")).strip()
    block = "\n".join([START, flow, "", f"@{os.path.join(vault, 'devflow', 'conventions.md')}", END])
    if START in current and END in current:
        before, rest = current.split(START, 1)
        after = rest.split(END, 1)[1]
        wanted = before + block + after
    elif current.strip():
        wanted = current.rstrip("\n") + "\n\n" + block + "\n"
    else:
        wanted = block + "\n"
    return current, wanted


def diff(label, old, new):
    return "".join(difflib.unified_diff(old.splitlines(True), new.splitlines(True), f"{label} (current)", f"{label} (new)"))


def backup(path):
    if not os.path.exists(path):
        return None
    os.makedirs(BACKUPS, exist_ok=True)
    stamp = datetime.datetime.now().strftime("%Y%m%d%H%M%S")
    target = os.path.join(BACKUPS, f"{os.path.basename(path)}.devflow-{stamp}")
    shutil.copy2(path, target)
    return target


def write(path, content):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(content)


def apply(args):
    if args.language not in languages():
        sys.exit(f"unknown language '{args.language}': {', '.join(languages())}")
    known = components()
    areas = [a.strip() for a in args.areas.split(",") if a.strip()]
    unknown = [a for a in areas if a not in known]
    if unknown:
        sys.exit(f"unknown areas: {', '.join(unknown)} (known: {', '.join(known)})")
    areas = sorted(set(areas) | {name for name, area in known.items() if area.get("required")})
    vault = os.path.abspath(os.path.expanduser(args.vault))
    if " " in vault:
        print(f"WARNING: the Vault path has spaces; the CLAUDE.md import may not resolve: {vault}")

    config_old = read_json(CONFIG, None)
    config_new = {"language": args.language, "vault": vault, "areas": areas}
    missing = vault_plan(args.language, vault)
    settings_old, settings_new = settings_plan(areas)
    md_old, md_new = claude_md_plan(vault)

    print("== config:", CONFIG)
    print(diff("config.json", json.dumps(config_old, indent=2) + "\n" if config_old else "", json.dumps(config_new, indent=2) + "\n") or "(no change)")
    print("== vault:", vault, "(exists)" if os.path.isdir(vault) else "(will be created)")
    print("\n".join(f"  + {rel}" for _, rel in missing) or "  (nothing missing)")
    print("== settings:", SETTINGS)
    print(diff("settings.json", json.dumps(settings_old, indent=2) + "\n", json.dumps(settings_new, indent=2) + "\n") or "(no change)")
    print("== CLAUDE.md:", CLAUDE_MD)
    print(diff("CLAUDE.md", md_old, md_new) or "(no change)")
    if importlib.util.find_spec("yaml") is None:
        print("WARNING: PyYAML is not installed; the knowledge Area needs it (pip install pyyaml).")

    if args.dry_run:
        print("\n(dry run: nothing written)")
        return

    write(CONFIG, json.dumps(config_new, indent=2) + "\n")
    for src, rel in missing:
        os.makedirs(os.path.dirname(os.path.join(vault, rel)), exist_ok=True)
        shutil.copy2(src, os.path.join(vault, rel))
    if settings_new != settings_old:
        saved = backup(SETTINGS)
        write(SETTINGS, json.dumps(settings_new, indent=2) + "\n")
        print(f"settings backup: {saved}")
    if md_new != md_old:
        saved = backup(CLAUDE_MD)
        write(CLAUDE_MD, md_new)
        print(f"CLAUDE.md backup: {saved}")
    print("\napplied")


def check():
    config = read_json(CONFIG, None)
    if not config or not config.get("vault"):
        problem = "devflow is installed but not set up on this machine."
    else:
        current, wanted = claude_md_plan(config["vault"])
        settings_old, settings_new = settings_plan(config.get("areas", []))
        missing = vault_plan(config.get("language", "en"), config["vault"])
        if current == wanted and settings_old == settings_new and not missing:
            return
        problem = "devflow was updated and this machine's setup is out of date."
    print(json.dumps({
        "systemMessage": f"{problem} Run /devflow:setup.",
        "hookSpecificOutput": {
            "hookEventName": "SessionStart",
            "additionalContext": f"{problem} If the user asks about devflow, tell them to run /devflow:setup first.",
        },
    }))


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("status")
    sub.add_parser("check", help="print a SessionStart hook message when the setup is missing or out of date")
    run = sub.add_parser("apply")
    run.add_argument("--language", required=True)
    run.add_argument("--vault", required=True)
    run.add_argument("--areas", required=True, help="comma-separated Areas to turn on")
    run.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()
    if args.command == "status":
        status()
    elif args.command == "check":
        check()
    else:
        apply(args)


if __name__ == "__main__":
    main()
